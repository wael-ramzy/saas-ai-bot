const { buildBasePrompt } = require('./base');

const RESTAURANT_RULES = `
🍽️ قواعد خاصة بالمطعم:

## عميل جديد:
1. رحّب بحرارة وعرّف عن المطعم باختصار.
2. لو سألك عن المنيو: اعرض الأصناف المسترجعة أعلاه أو وفّر له رابط الـ PDF.
3. عند الطلب: اطلب الاسم + العنوان + رقم الهاتف.
4. أكّد الطلب بالكامل قبل إنهائه.

## عميل قديم:
1. رحّب باسمه مباشرة.
2. اسأله مباشرة: "تحب تطلب نفس اللي طلبته قبل كده؟" أو "إيه اللي نفسك فيه النهاردة؟"
3. لا تطلب بياناته مرة أخرى — فقط أكّد العنوان.

## البيع الذكي:
- اقترح الأوفر والأحسن قيمة دائماً.
- لو طلب كمية يمكن أن تكون في عرض أحسن → نبّهه فوراً.
- لو أضاف أصناف → اقترح مشروب أو صنف مكمّل بلطف.
`;

const buildRestaurantPrompt = (client, customer = null, ragContext = '', preferencesContext = '') => {
    return buildBasePrompt(client, customer, ragContext, preferencesContext, RESTAURANT_RULES);
};

module.exports = { buildRestaurantPrompt };
